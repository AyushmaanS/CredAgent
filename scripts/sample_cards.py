"""Regenerate docs/samples/handoff-cards.md from real offline fake-provider runs (no API keys needed).

    .venv/bin/python scripts/sample_cards.py

Each scenario runs in headless Chrome against Fakeprov with the offline deciders. A harness plays the
person (the same one the browser tests use), and every card the agent prints is written out verbatim.
"""

from __future__ import annotations

import asyncio
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tests.integration.test_browser_loop_fake import faulty, run_scenario  # noqa: E402

OUT = ROOT / "docs" / "samples" / "handoff-cards.md"
CASES = [
    ("terms_checkbox", "DO: terms checkbox (the agent filled the form; only the person accepts terms)", {}),
    ("terms_implied", "DO: implied agreement (“By clicking Create app, you agree…”)", {}),
    ("signin_resume", "DO: sign-in wall", {}),
    ("captcha", "DO: CAPTCHA / human check", {}),
    ("cookie_accept_only", "DO: cookie banner with no limited option", {}),
    ("decide_app_type_and_scopes", "DECIDE: choosing the application type",
     {"extra_steps": [{"kind": "click", "description": "Choose the application type"}]}),
    ("jev_failure", "DECIDE: Jev unavailable, so the risk of “Create app” is unknown and assumed hard to undo",
     "faulty"),
]
PORT = re.compile(r"127\.0\.0\.1:\d+")


async def cards_for(name: str, kw: dict | str) -> list[str]:
    if kw == "faulty":
        jev, llm = faulty(name)
        kw = {"jev": jev, "reasoner": llm}
    with tempfile.TemporaryDirectory() as tmp:
        _result, _run, io, *_ = await run_scenario(Path(tmp), name, **kw)
    return [PORT.sub("127.0.0.1:PORT", t) for t in io.out if t.startswith("=")]


def main() -> None:
    parts = ["# Sample handoff cards", "",
             "Generated by `scripts/sample_cards.py` from real offline runs against the fake provider "
             "(headless Chrome, offline deciders, a harness playing the person). The text is exactly what the "
             "terminal shows; only the local port is replaced with `PORT`. Every card has the six fields "
             "required by PRD §9: done so far, blocking + evidence, what to do and where, what the agent does "
             "next, how to resume, and what not to do.", ""]
    for name, title, kw in CASES:
        cards = asyncio.run(cards_for(name, kw))
        parts += [f"## {title}", "", f"Scenario: `{name}` · try it: "
                  f"`.venv/bin/credagent get Fakeprov --fake-provider {name} --offline`", ""]
        for c in cards[:1]:
            parts += ["```text", c, "```", ""]
        print(f"{name}: {len(cards)} card(s)")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
